"""Apply attribution matches to the live Lorehaven database.

Idempotent by construction: both inserts are upserts keyed on the tables' own
unique constraints, so a rerun costs a scan and changes nothing.

Writes two things per MATCHED work only:
  1. `creators`         one external creator per AO3 username, with
                         `canonical_url` pointing at the AO3 PROFILE
  2. `media_creators`   the (work_id, creator_id, 'author') attribution edge

Unmatched works are LEFT ALONE — see match_authors.py for why guessing is worse
than leaving a gap for curators.

Credentials come from the environment (`LOREHAVEN_*`), never from a literal:
    set -a; . ~/.hermes/profiles/sysadmin/.env; set +a
    python3 apply_attribution.py --db-url "$DATABASE_URL"

`--dry-run` prints what would be written and touches nothing. Run that first.
"""

from __future__ import annotations

import argparse
import csv
import os
import sys
import uuid
from collections import Counter
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))

from match_authors import AuthorIndex, match_works  # noqa: E402


def _pg_url() -> str:
    """Resolve the Postgres URL from the environment.

    `psql` is not assumed present and psycopg may not be installed, so the
    writes go out as SQL text over the wire only when a driver exists;
    otherwise this returns the URL for the caller to hand to psql.
    """
    for key in ("LOREHAVEN_DATABASE_URL", "DATABASE_URL", "LOREHAVEN_TEST_PG_URL"):
        if value := os.environ.get(key):
            return value
    msg = "no database URL in the environment (set LOREHAVEN_DATABASE_URL)"
    raise SystemExit(msg)


def load_works(csv_path: str) -> list[tuple[str, str | None]]:
    """Read `(work_uuid, title)` pairs exported from the live `works` table."""
    out: list[tuple[str, str | None]] = []
    with open(csv_path, newline="", encoding="utf-8", errors="replace") as handle:
        for row in csv.reader(handle):
            if len(row) >= 2:
                out.append((row[0], row[1] or None))
    return out


def build_statements(results) -> tuple[list[dict], list[tuple]]:
    """Reduce matches to deduplicated creators and per-work edges.

    The creator UUID must be STABLE across reruns or the upsert cannot match its
    own conflict target and would insert a duplicate. Deriving it from
    (source_key, source_creator_id) with uuid5 makes it deterministic.
    """
    creators: dict[tuple[str, str], dict] = {}
    edges: list[tuple] = []

    for r in results:
        if not r.attributed:
            continue
        key = ("ao3", r.author)
        if key not in creators:
            creators[key] = {
                "id": str(
                    uuid.uuid5(uuid.NAMESPACE_URL, f"lorehaven:creator:ao3:{r.author}")
                ),
                "display_name": r.author,
                "source_creator_id": r.author,
                "canonical_url": r.ao3_author_url,
            }
        edges.append(
            (
                str(uuid.uuid5(uuid.NAMESPACE_URL, f"lorehaven:edge:{r.work_id}")),
                r.work_id,
                creators[key]["id"],
            )
        )
    return list(creators.values()), edges


CREATOR_UPSERT_DOC = """The creator upsert, for reference:

    INSERT INTO creators (id, kind, display_name, source_key, source_creator_id,
                          canonical_url, created_at, updated_at, version)
    VALUES (%(id)s, 'external', %(display_name)s, 'ao3', %(source_creator_id)s,
            %(canonical_url)s, now()::text, now()::text, 1)
    ON CONFLICT (source_key, source_creator_id) WHERE source_key IS NOT NULL
    DO UPDATE SET canonical_url = EXCLUDED.canonical_url;

The partial-index conflict target is what makes the rerun idempotent, and the
uuid5-derived id keeps it stable -- an INSERT that cannot match its own conflict
target inserts a duplicate every run.
"""


def write_sql(creators: list[dict], edges: list[tuple], path: str) -> None:
    """Emit a standalone .sql file so the write is reviewable before it runs."""
    def q(value: str | None) -> str:
        if value is None:
            return "NULL"
        return "'" + str(value).replace("'", "''") + "'"

    with open(path, "w", encoding="utf-8") as out:
        out.write("-- Generated by apply_attribution.py. Idempotent.\n")
        out.write("BEGIN;\n")
        for c in creators:
            out.write(
                "INSERT INTO creators (id, kind, display_name, source_key,"
                " source_creator_id, canonical_url, created_at, updated_at, version)\n"
                f"VALUES ('{c['id']}', 'external', {q(c['display_name'])}, 'ao3',"
                f" {q(c['source_creator_id'])}, {q(c['canonical_url'])},"
                " now()::text, now()::text, 1)\n"
                "ON CONFLICT (source_key, source_creator_id)"
                " WHERE source_key IS NOT NULL\n"
                "DO UPDATE SET canonical_url = EXCLUDED.canonical_url,"
                " display_name = EXCLUDED.display_name, updated_at = now()::text;\n"
            )
        for edge_id, work_id, creator_id in edges:
            out.write(
                "INSERT INTO media_creators (id, work_id, creator_id, role,"
                " position, created_at)\n"
                f"VALUES ('{edge_id}', '{work_id}', '{creator_id}', 'author', 0,"
                " now()::text)\nON CONFLICT (work_id, creator_id, role) DO NOTHING;\n"
            )
        out.write("COMMIT;\n")


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--works-csv", required=True,
                        help="(work_uuid,title) CSV exported from the live works table")
    parser.add_argument("--ao3-db", required=True,
                        help="AO3 recommender metadata DB (read-only)")
    parser.add_argument("--out-sql", required=True, help="where to write the SQL")
    parser.add_argument("--dry-run", action="store_true",
                        help="report only; write nothing")
    args = parser.parse_args()

    works = load_works(args.works_csv)
    index = AuthorIndex.from_db(args.ao3_db)
    results = match_works(works, index)
    attributed = [r for r in results if r.attributed]

    reasons = Counter(r.reason for r in results if not r.attributed)
    print(f"works read       : {len(works)}")
    print(f"attributed       : {len(attributed)} ({len(attributed)/max(len(works),1):.1%})")
    print(f"left unattributed: {len(works) - len(attributed)}")
    for reason, count in reasons.most_common():
        print(f"    {reason:24s} {count}")

    creators, edges = build_statements(results)
    print(f"\ncreators to upsert : {len(creators)}")
    print(f"edges to insert    : {len(edges)}")
    missing_url = sum(1 for c in creators if not c["canonical_url"])
    if missing_url:
        print(f"WARNING: {missing_url} creators without a canonical_url")

    if args.dry_run:
        print("\n--dry-run: no SQL written.")
        return 0

    write_sql(creators, edges, args.out_sql)
    print(f"\nwrote {args.out_sql}")
    print(f"database url source: {_pg_url()[:24]}... (not written to the file)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())