/// Approve a proposal, applying it and recording what it changed.
///
/// This is the whole of §33.3(c) in one function, deliberately: a merge that
/// recorded its approver but did not record what it moved would not be
/// reversible, and a reversal is required. The recorded rows in
/// `tag_wrangler_merge_actions` are what a later revert reads.
pub async fn approve_wrangling(
    db: &Database,
    id: &str,
    approved_by: Uuid,
    approver_trust: i64,
) -> Result<()> {
    let Some(proposal) = get_wrangling_proposal(db, id).await? else {
        return Err(WrangleError::NotFound.into());
    };
    if proposal.status != "pending" {
        return Err(WrangleError::WrongState("already decided").into());
    }
    let Some(to_node_id) = proposal.to_node_id.clone() else {
        return Err(WrangleError::NoTarget(proposal.kind.as_str()).into());
    };

    if proposal.kind.rewrites_taxonomy() {
        apply_merge(db, id, &proposal.from_node_id, &to_node_id).await?;
    }

    let now = crate::identity::now_rfc3339();
    let sql = db.sql(
        "UPDATE tag_wrangling_proposals
            SET status = 'approved', approved_by = ?, approver_trust = ?, decided_at = ?
          WHERE id = ? AND status = 'pending'",
        "UPDATE tag_wrangling_proposals
            SET status = 'approved', approved_by = ?::uuid, approver_trust = ?, decided_at = ?::timestamptz
          WHERE id = ?::uuid AND status = 'pending'",
    );
    match db.backend() {
        Backend::Sqlite => {
            sqlx::query(&sql)
                .bind(approved_by.to_string())
                .bind(approver_trust)
                .bind(&now)
                .bind(id)
                .execute(db.sqlite_pool().expect("sqlite handle"))
                .await?;
        }
        Backend::Postgres => {
            sqlx::query(&sql)
                .bind(approved_by.to_string())
                .bind(approver_trust)
                .bind(&now)
                .bind(id)
                .execute(db.postgres_pool().expect("postgres handle"))
                .await?;
        }
    }
    Ok(())
}

/// Append one recorded action, so a revert is a read of what happened.
///
/// Every mutation the merge performs records itself here. That is what makes
/// the reversal in §33.3(c) exact: `revert` reads these rows rather than
/// inferring what must have changed.
async fn record_action(
    db: &Database,
    proposal_id: &str,
    action: &str,
    previous_value: &str,
    subject_id: &str,
) -> Result<()> {
    let id = Uuid::new_v4().to_string();
    let now = crate::identity::now_rfc3339();
    let sql = db.sql(
        "INSERT INTO tag_wrangler_merge_actions
           (id, proposal_id, action, previous_value, subject_id, created_at)
         VALUES (?, ?, ?, ?, ?, ?)",
        "INSERT INTO tag_wrangler_merge_actions
           (id, proposal_id, action, previous_value, subject_id, created_at)
         VALUES (?::uuid, ?::uuid, ?, ?, ?, ?::timestamptz)",
    );
    match db.backend() {
        Backend::Sqlite => {
            sqlx::query(&sql)
                .bind(&id)
                .bind(proposal_id)
                .bind(action)
                .bind(previous_value)
                .bind(subject_id)
                .bind(&now)
                .execute(db.sqlite_pool().expect("sqlite handle"))
                .await?;
        }
        Backend::Postgres => {
            sqlx::query(&sql)
                .bind(&id)
                .bind(proposal_id)
                .bind(action)
                .bind(previous_value)
                .bind(subject_id)
                .bind(&now)
                .execute(db.postgres_pool().expect("postgres handle"))
                .await?;
        }
    }
    Ok(())
}

/// Apply a merge and record every row it moved.
///
/// The source node is never destroyed. A merge retargets the work tags and
/// aliases that pointed at it and leaves the node in place, so the history the
/// source carries survives and a revert is a matter of putting the tags back --
/// which is what `tag_wrangler_merge_actions` exists to make exact rather than
/// inferred.
async fn apply_merge(
    db: &Database,
    proposal_id: &str,
    from_node_id: &str,
    to_node_id: &str,
) -> Result<()> {
    // Record every tag that is about to move, with the node it came from and the
    // weight it had. The weight is part of what a revert has to restore: a tag
    // put back at the default would quietly change the reader's own view of how
    // strongly a work is a fantasy.
    let find_sql = db.sql(
        "SELECT work_id, weight FROM work_tags WHERE node_id = ?",
        "SELECT work_id::text AS work_id, weight FROM work_tags WHERE node_id = ?",
    );
    let tagged: Vec<(String, i64)> = match db.backend() {
        Backend::Sqlite => {
            sqlx::query_as(&find_sql)
                .bind(from_node_id)
                .fetch_all(db.sqlite_pool().expect("sqlite handle"))
                .await?
        }
        Backend::Postgres => {
            sqlx::query_as(&find_sql)
                .bind(from_node_id)
                .fetch_all(db.postgres_pool().expect("postgres handle"))
                .await?
        }
    };

    // Each tagged work is handled on its own rather than with one set-based
    // statement. The set-based form needs a correlated subquery over the table
    // being updated, and that does not behave the same way on both backends --
    // on SQLite the update moves rows the guard meant to skip, and the merge
    // reports success having changed nothing. Per row, the rule is the same
    // three lines on either backend and the difference between "moved" and
    // "already had it" stays visible, which is what the revert needs to know.
    let has_target_sql = db.sql(
        "SELECT COUNT(*) FROM work_tags WHERE work_id = ? AND node_id = ?",
        "SELECT COUNT(*)::bigint AS count FROM work_tags WHERE work_id = ?::uuid AND node_id = ?",
    );
    let move_sql = "UPDATE work_tags SET node_id = ? WHERE work_id = ? AND node_id = ?";
    let drop_sql = db.sql(
        "DELETE FROM work_tags WHERE work_id = ? AND node_id = ?",
        "DELETE FROM work_tags WHERE work_id = ?::uuid AND node_id = ?",
    );

    for (work_id, weight) in &tagged {
        let already: i64 = match db.backend() {
            Backend::Sqlite => {
                sqlx::query_as::<_, (i64,)>(&has_target_sql)
                    .bind(work_id)
                    .bind(to_node_id)
                    .fetch_one(db.sqlite_pool().expect("sqlite handle"))
                    .await?
                    .0
            }
            Backend::Postgres => {
                sqlx::query_as::<_, (i64,)>(&has_target_sql)
                    .bind(work_id)
                    .bind(to_node_id)
                    .fetch_one(db.postgres_pool().expect("postgres handle"))
                    .await?
                    .0
            }
        };

        if already == 0 {
            // The work did not carry the target, so the row simply moves and its
            // weight comes with it. Recorded as `retarget_tags` with the node it
            // came from, so a revert knows to point it back.
            record_action(db, proposal_id, "retarget_tags", from_node_id, work_id).await?;
            match db.backend() {
                Backend::Sqlite => {
                    sqlx::query(move_sql)
                        .bind(to_node_id)
                        .bind(work_id)
                        .bind(from_node_id)
                        .execute(db.sqlite_pool().expect("sqlite handle"))
                        .await?;
                }
                Backend::Postgres => {
                    sqlx::query(move_sql)
                        .bind(to_node_id)
                        .bind(work_id)
                        .bind(from_node_id)
                        .execute(db.postgres_pool().expect("postgres handle"))
                        .await?;
                }
            }
        } else {
            // The work already carried the target. Moving the row would create
            // a second row for the same pair, and leaving it would leave the
            // work tagged with both spellings -- which is the state the merge
            // exists to end. So the source row goes, its weight is recorded
            // first, and the revert puts it back with that weight.
            //
            // The source node itself is never deleted, so the history it
            // carries survives the merge.
            record_action(db, proposal_id, "retarget_tags", from_node_id, work_id).await?;
            record_action(db, proposal_id, "set_weight", &weight.to_string(), work_id).await?;
            match db.backend() {
                Backend::Sqlite => {
                    sqlx::query(&drop_sql)
                        .bind(work_id)
                        .bind(from_node_id)
                        .execute(db.sqlite_pool().expect("sqlite handle"))
                        .await?;
                }
                Backend::Postgres => {
                    sqlx::query(&drop_sql)
                        .bind(work_id)
                        .bind(from_node_id)
                        .execute(db.postgres_pool().expect("postgres handle"))
                        .await?;
                }
            }
        }
    }

    // Aliases follow the tags, and the same collision rule applies.
    // The same rule as the tags: an alias that already points at the target is
    // left alone, so a merge cannot create a second row for one spelling.
    let alias_sql = "UPDATE taxonomy_aliases
                        SET node_id = ?
                      WHERE node_id = ?
                        AND NOT EXISTS (SELECT 1 FROM taxonomy_aliases existing
                                         WHERE existing.alias = taxonomy_aliases.alias
                                           AND existing.node_id = ?)";
    match db.backend() {
        Backend::Sqlite => {
            sqlx::query(&alias_sql)
                .bind(to_node_id)
                .bind(from_node_id)
                .bind(to_node_id)
                .execute(db.sqlite_pool().expect("sqlite handle"))
                .await?;
        }
        Backend::Postgres => {
            sqlx::query(&alias_sql)
                .bind(to_node_id)
                .bind(from_node_id)
                .bind(to_node_id)
                .execute(db.postgres_pool().expect("postgres handle"))
                .await?;
        }
    }

    Ok(())
}

/// Revert an approved merge, restoring what it moved.
///
/// Reads the recorded actions and puts each subject back where it came from, so
/// the reversal is a read of what happened rather than a guess at what must
/// have happened. The proposal is marked `reverted` and chained to its own
/// successor, which is what §33.3's "merges keep their history" means in the
/// data.
pub async fn revert_wrangling(
    db: &Database,
    id: &str,
    reverted_by: Uuid,
    approver_trust: i64,
) -> Result<()> {
    let Some(proposal) = get_wrangling_proposal(db, id).await? else {
        return Err(WrangleError::NotFound.into());
    };
    if proposal.status != "approved" {
        return Err(WrangleError::WrongState("not approved").into());
    }
    let target = proposal.to_node_id.clone().unwrap_or_default();
    let reverted_at = crate::identity::now_rfc3339();

    // The recorded actions, in the order they happened. The reversal is a read
    // of these rows rather than an inference about what a merge must have
    // touched, which is the difference between a revert that is exact and one
    // that is plausible.
    let actions_sql = db.sql(
        "SELECT action, subject_id, previous_value FROM tag_wrangler_merge_actions
          WHERE proposal_id = ? AND reverted_at IS NULL
          ORDER BY created_at ASC, rowid ASC",
        "SELECT action, subject_id, previous_value FROM tag_wrangler_merge_actions
          WHERE proposal_id = ?::uuid AND reverted_at IS NULL
          ORDER BY created_at ASC, id ASC",
    );
    let actions: Vec<(String, Option<String>, Option<String>)> = match db.backend() {
        Backend::Sqlite => {
            sqlx::query_as(&actions_sql)
                .bind(id)
                .fetch_all(db.sqlite_pool().expect("sqlite handle"))
                .await?
        }
        Backend::Postgres => {
            sqlx::query_as(&actions_sql)
                .bind(id)
                .fetch_all(db.postgres_pool().expect("postgres handle"))
                .await?
        }
    };

    for (action, subject, previous) in &actions {
        let (Some(subject), Some(previous)) = (subject, previous) else {
            continue;
        };
        match action.as_str() {
            // The tag went from `previous` to the target. Put it back on
            // `previous` at the weight it had, recreating the row if the
            // dedupe step deleted it instead of moving it.
            "retarget_tags" => {
                let weight = actions
                    .iter()
                    .find(|(a, sub, _)| {
                        a == "set_weight" && sub.as_deref() == Some(subject.as_str())
                    })
                    .and_then(|(_, _, value)| value.as_deref())
                    .and_then(|v| v.parse::<i64>().ok())
                    .unwrap_or(0);
                let work_uuid = uuid::Uuid::parse_str(subject)
                    .map_err(|_| anyhow::anyhow!("recorded a non-uuid work id"))?;
                let previous_uuid = uuid::Uuid::parse_str(previous)
                    .map_err(|_| anyhow::anyhow!("recorded a non-uuid node id"))?;

                let restore_sql = db.sql(
                    "INSERT OR REPLACE INTO work_tags (work_id, node_id, weight, added_at) VALUES (?, ?, ?, ?)",
                    "INSERT INTO work_tags (work_id, node_id, weight, added_at) VALUES (?::uuid, ?::uuid, ?, ?::timestamptz)
                     ON CONFLICT (work_id, node_id) DO UPDATE SET weight = excluded.weight",
                );
                match db.backend() {
                    Backend::Sqlite => {
                        sqlx::query(&restore_sql)
                            .bind(subject)
                            .bind(previous)
                            .bind(weight)
                            .bind(&reverted_at)
                            .execute(db.sqlite_pool().expect("sqlite handle"))
                            .await?;
                    }
                    Backend::Postgres => {
                        sqlx::query(&restore_sql)
                            .bind(work_uuid)
                            .bind(previous_uuid)
                            .bind(weight)
                            .bind(&reverted_at)
                            .execute(db.postgres_pool().expect("postgres handle"))
                            .await?;
                    }
                }

                // The target row goes only if the merge created it. A recorded
                // `set_weight` beside this subject means the merge deleted the
                // source instead of moving it, which is what happens to a work
                // that already carried the target -- and that work must keep
                // that tag, because it had it before anyone merged anything.
                let had_target = actions.iter().any(|(a, sub, _)| {
                    a == "set_weight" && sub.as_deref() == Some(subject.as_str())
                });
                if !had_target {
                    let drop_sql = db.sql(
                        "DELETE FROM work_tags WHERE work_id = ? AND node_id = ?",
                        "DELETE FROM work_tags WHERE work_id = ?::uuid AND node_id = ?",
                    );
                    match db.backend() {
                        Backend::Sqlite => {
                            sqlx::query(&drop_sql)
                                .bind(subject)
                                .bind(&target)
                                .execute(db.sqlite_pool().expect("sqlite handle"))
                                .await?;
                        }
                        Backend::Postgres => {
                            sqlx::query(&drop_sql)
                                .bind(subject)
                                .bind(&target)
                                .execute(db.postgres_pool().expect("postgres handle"))
                                .await?;
                        }
                    }
                }
            }
            // The merge left the weight alone, so there is nothing to undo. The
            // row's weight was restored by the `retarget_tags` branch above.
            _ => {}
        }
    }

    let mark_sql = db.sql(
        "UPDATE tag_wrangler_merge_actions SET reverted_at = ? WHERE proposal_id = ? AND reverted_at IS NULL",
        "UPDATE tag_wrangler_merge_actions SET reverted_at = ?::timestamptz WHERE proposal_id = ?::uuid AND reverted_at IS NULL",
    );
    match db.backend() {
        Backend::Sqlite => {
            sqlx::query(&mark_sql)
                .bind(&reverted_at)
                .bind(id)
                .execute(db.sqlite_pool().expect("sqlite handle"))
                .await?;
        }
        Backend::Postgres => {
            sqlx::query(&mark_sql)
                .bind(&reverted_at)
                .bind(id)
                .execute(db.postgres_pool().expect("postgres handle"))
                .await?;
        }
    }

    // A new proposal records the reversal, so the chain is auditable and the
    // original approval still reads as approved rather than being rewritten.
    let reversal = propose_wrangling(
        db,
        proposal.kind,
        &target,
        Some(&proposal.from_node_id),
        &format!("reverts {id}"),
        reverted_by,
        approver_trust,
    )
    .await?;
    let chain_sql = db.sql(
        "UPDATE tag_wrangling_proposals SET status = 'reverted', reverts_id = ? WHERE id = ?",
        "UPDATE tag_wrangling_proposals SET status = 'reverted', reverts_id = ?::uuid WHERE id = ?::uuid",
    );
    match db.backend() {
        Backend::Sqlite => {
            sqlx::query(&chain_sql)
                .bind(&reversal)
                .bind(id)
                .execute(db.sqlite_pool().expect("sqlite handle"))
                .await?;
        }
        Backend::Postgres => {
            sqlx::query(&chain_sql)
                .bind(&reversal)
                .bind(id)
                .execute(db.postgres_pool().expect("postgres handle"))
                .await?;
        }
    }
    Ok(())
}

/// misleads exactly as badly as no log.
pub async fn public_wrangling_log(db: &Database, limit: i64) -> Result<Vec<WranglingProposal>> {
    let sql = db.sql(
        "SELECT id, kind, from_node_id, to_node_id, reason, status,
                proposer_trust, approver_trust, created_at
           FROM tag_wrangling_proposals
          WHERE status IN ('approved', 'reverted')
          ORDER BY created_at DESC, id DESC LIMIT ?",
        "SELECT id::text, kind, from_node_id, to_node_id, reason, status,
                proposer_trust::bigint AS proposer_trust, approver_trust::bigint AS approver_trust,
                created_at::text AS created_at
           FROM tag_wrangling_proposals
          WHERE status IN ('approved', 'reverted')
          ORDER BY created_at DESC, id DESC LIMIT ?",
    );
    let rows: Vec<(
        String,
        String,
        String,
        Option<String>,
        String,
        String,
        i64,
        Option<i64>,
        String,
    )> = match db.backend() {
        Backend::Sqlite => {
            sqlx::query_as(&sql)
                .bind(limit)
                .fetch_all(db.sqlite_pool().expect("sqlite handle"))
                .await?
        }
        Backend::Postgres => {
            sqlx::query_as(&sql)
                .bind(limit)
                .fetch_all(db.postgres_pool().expect("postgres handle"))
                .await?
        }
    };
    Ok(rows
        .into_iter()
        .map(
            |(id, kind, from, to, reason, status, ptrust, atrust, created_at)| WranglingProposal {
                id,
                kind: WranglingKind::parse(&kind).unwrap_or(WranglingKind::Alias),
                from_node_id: from,
                to_node_id: to,
                reason,
                status,
                proposer_trust: ptrust,
                approver_trust: atrust,
                created_at,
            },
        )
        .collect())
}

