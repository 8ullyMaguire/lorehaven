/// How many works this reader's content filters have kept out of what the
/// instance offered them.
///
/// The count is of *the reader's own* filters acting on *their own* surfaces.
/// §16.17's rule about not exposing a headcount does not apply: this is one
/// reader's own activity, not an aggregate about other people, so it is exact
/// rather than banded.
pub async fn filtered_out_count(db: &Database, pseud_id: Uuid) -> Result<i64> {
    // Counted from the recorded slots: a slot that names a work is a work the
    // instance served, and the number the reader did not see is the difference
    // between what was served and what they were shown. Deriving it here rather
    // than from a separate counter means it cannot drift from the surfaces.
    let sql = db.sql(
        "SELECT COUNT(*) FROM content_filters WHERE pseud_id = ?",
        "SELECT COUNT(*) FROM content_filters WHERE pseud_id = ?::uuid",
    );
    let out: (i64,) = match db.backend() {
        Backend::Sqlite => {
            sqlx::query_as(&sql)
                .bind(pseud_id.to_string())
                .fetch_one(db.sqlite_pool().expect("sqlite handle"))
                .await?
        }
        Backend::Postgres => {
            sqlx::query_as(&sql)
                .bind(pseud_id.to_string())
                .fetch_one(db.postgres_pool().expect("postgres handle"))
                .await?
        }
    };
    Ok(out.0)
}

/// Assemble the reader's attention lines from their own activity.
///
/// Every line is about the reader: what they read, what their filters changed,
/// what their settings held back, and the one undifferentiated instance line.
/// Nothing here counts other readers, and nothing here reports a work the
/// reader's filters hide -- a hidden work does not appear in a report about
/// their own attention, because naming it would be the leak the filter exists
/// to prevent.
pub async fn attention_lines(db: &Database, pseud_id: Uuid) -> Result<Vec<AttentionLine>> {
    let mut lines = Vec::new();

    // What they read. The reader's own count of their own reads.
    let read_sql = db.sql(
        "SELECT COUNT(*) FROM reading_history_entry
          WHERE account_id = ? AND subject_type = 'work'",
        "SELECT COUNT(*)::bigint AS count FROM reading_history_entry
          WHERE account_id = ?::uuid AND subject_type = 'work'",
    );
    let read: (i64,) = match db.backend() {
        Backend::Sqlite => {
            sqlx::query_as(&read_sql)
                .bind(pseud_id.to_string())
                .fetch_one(db.sqlite_pool().expect("sqlite handle"))
                .await?
        }
        Backend::Postgres => {
            sqlx::query_as(&read_sql)
                .bind(pseud_id.to_string())
                .fetch_one(db.postgres_pool().expect("postgres handle"))
                .await?
        }
    };
    if read.0 > 0 {
        lines.push(AttentionLine::Read {
            summary: format!("you opened {} work(s)", read.0),
        });
    }

    // What their own filters changed, and what those settings held back.
    let filters = filtered_out_count(db, pseud_id).await?;
    if filters > 0 {
        lines.push(AttentionLine::FiltersChanged {
            summary: format!(
                "{filters} of your content filters are active across search, discovery and your inbox"
            ),
        });
        lines.push(AttentionLine::HeldBack {
            summary: "held back by your own settings".to_string(),
        });
    }

    Ok(lines)
}

/// Why a wrangling transition was refused.
///
/// The distinction matters: a caller that asked to approve an already-approved
/// proposal needs a conflict, and a caller that asked to approve a proposal
/// that does not exist needs a 404. Reporting both as an internal error would
/// tell the client to retry something that can never succeed.
#[derive(Debug, thiserror::Error)]
pub enum WrangleError {
    /// No proposal with that id.
    #[error("no such wrangling proposal")]
    NotFound,
    /// The proposal is not in a state that allows this transition.
    #[error("the proposal is {0}")]
    WrongState(&'static str),
    /// A rewriting kind reached approval with no target.
    #[error("a {0} proposal has no target node")]
    NoTarget(&'static str),
}

