//! M29 — recommendation transparency, DB layer (spec §33.3).
//!
//! Records what a recommendation slot was and why, at the moment it was served,
//! and answers "why am I seeing this" afterwards from the recorded row rather
//! than by replaying the blend. The design reason is in the migration's header:
//! `time_decay_strategy` reads the clock inside its scoring query, so a
//! recomputed explanation would be a plausible-looking lie.
//!
//! Every read here is scoped by `pseud_id`. §33.3(b) makes the attention report
//! private to its reader, and §33.3's last acceptance criterion says no
//! proposal or vote is visible in another user's surface — so the scoping is in
//! the WHERE of every statement, never applied afterwards.

use anyhow::Result;
use uuid::Uuid;

use lorehaven_domain::recommendation_transparency::{
    AttentionLine, InstanceCuration, SlotExplanation, SlotReason, TasteSignal, WranglingKind,
    WranglingProposal,
};

use crate::{Backend, Database};

// ---------------------------------------------------------------------------
// Recording slots
// ---------------------------------------------------------------------------

/// What the app layer knows about a served slot at record time.
///
/// The reasons are already the closed vocabulary, so this struct cannot carry a
/// string a handler invented.
#[derive(Debug, Clone)]
pub struct SlotRecord {
    pub pseud_id: Uuid,
    pub work_id: Uuid,
    pub request_id: Uuid,
    pub position: i64,
    pub reasons: Vec<SlotReason>,
    pub taste_signal: Option<TasteSignal>,
    pub seeded_by: Option<String>,
    pub recipe_stage: Option<String>,
    pub instance_curation: InstanceCuration,
    pub blend_score: i64,
}

/// Record one served slot and return its id.
///
/// The id is returned rather than generated by the caller so the app layer does
/// not have to know the shape, and so a caller that records several slots for
/// one response gets the ids back to put in the response it is about to send.
pub async fn record_slot(db: &Database, rec: &SlotRecord) -> Result<String> {
    let id = Uuid::new_v4().to_string();
    let now = crate::identity::now_rfc3339();
    // The reasons are stored as the vocabulary's wire forms, so a row written
    // by this version is readable by the next one without a mapping table.
    let reasons_json =
        serde_json::to_string(&rec.reasons.iter().map(|r| r.as_str()).collect::<Vec<_>>())
            .unwrap_or_else(|_| "[]".to_string());

    let sql = db.sql(
        "INSERT INTO recommendation_slots
           (id, pseud_id, work_id, request_id, position, reasons, taste_signal,
            seeded_by, recipe_stage, instance_curation, blend_score, created_at)
         VALUES (?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?)",
        // `reasons` is JSONB on PostgreSQL and TEXT on SQLite, and the row is
        // read back as a String, so each arm casts on its own side: the
        // placeholder on PG, nothing on SQLite (which has no :: syntax at all).
        "INSERT INTO recommendation_slots
           (id, pseud_id, work_id, request_id, position, reasons, taste_signal,
            seeded_by, recipe_stage, instance_curation, blend_score, created_at)
         VALUES (?::uuid, ?::uuid, ?::uuid, ?::uuid, ?, ?::jsonb, ?, ?, ?, ?, ?, ?::timestamptz)",
    );

    match db.backend() {
        Backend::Sqlite => {
            sqlx::query(&sql)
                .bind(&id)
                .bind(rec.pseud_id.to_string())
                .bind(rec.work_id.to_string())
                .bind(rec.request_id.to_string())
                .bind(rec.position)
                .bind(&reasons_json)
                .bind(rec.taste_signal.map(|t| t.as_str().to_string()))
                .bind(&rec.seeded_by)
                .bind(&rec.recipe_stage)
                .bind(rec.instance_curation.as_str())
                .bind(rec.blend_score)
                .bind(&now)
                .execute(db.sqlite_pool().expect("sqlite handle"))
                .await?;
        }
        Backend::Postgres => {
            sqlx::query(&sql)
                .bind(&id)
                .bind(rec.pseud_id.to_string())
                .bind(rec.work_id.to_string())
                .bind(rec.request_id.to_string())
                .bind(rec.position)
                .bind(&reasons_json)
                .bind(rec.taste_signal.map(|t| t.as_str().to_string()))
                .bind(&rec.seeded_by)
                .bind(&rec.recipe_stage)
                .bind(rec.instance_curation.as_str())
                .bind(rec.blend_score)
                .bind(&now)
                .execute(db.postgres_pool().expect("postgres handle"))
                .await?;
        }
    }
    Ok(id)
}

/// Record a whole served page, returning the slot ids in position order.
///
/// One call so a response cannot be sent with a slot id that was never written:
/// the ids come back from the insert, not from a parallel loop the caller might
/// reorder.
pub async fn record_response(
    db: &Database,
    pseud_id: Uuid,
    request_id: Uuid,
    slots: &[SlotRecord],
) -> Result<Vec<String>> {
    let mut ids = Vec::with_capacity(slots.len());
    for rec in slots {
        let mut rec = rec.clone();
        rec.pseud_id = pseud_id;
        rec.request_id = request_id;
        ids.push(record_slot(db, &rec).await?);
    }
    Ok(ids)
}

/// The explanation for one slot, or `None` if the reader does not own it.
///
/// `pseud_id` is the caller's, and the comparison is in the WHERE, so asking
/// about another reader's slot is a miss rather than a leak — the door answers
/// 404 either way, which is what §3.3 requires for an object the caller cannot
/// read.
pub async fn explain_slot(
    db: &Database,
    pseud_id: Uuid,
    slot_id: &str,
) -> Result<Option<SlotExplanation>> {
    let sql = db.sql(
        "SELECT id, work_id, position, reasons, taste_signal, seeded_by, recipe_stage,
                instance_curation, blend_score, created_at
           FROM recommendation_slots
          WHERE id = ? AND pseud_id = ?",
        // `reasons` is JSONB here and read as a String, so the column carries
        // the cast. Every uuid column is cast on the placeholder side, and
        // `position`/`blend_score` are INTEGER/BIGINT so they need nothing --
        // they are read into i64, which sqlx decodes from either.
        "SELECT id::text, work_id::text, position, reasons::text AS reasons, taste_signal,
                seeded_by, recipe_stage, instance_curation, blend_score::bigint AS blend_score,
                created_at::text AS created_at
           FROM recommendation_slots
          WHERE id = ?::uuid AND pseud_id = ?::uuid",
    );
    let row: Option<(
        String,
        String,
        i64,
        String,
        Option<String>,
        Option<String>,
        Option<String>,
        String,
        i64,
        String,
    )> = match db.backend() {
        Backend::Sqlite => {
            sqlx::query_as(&sql)
                .bind(slot_id)
                .bind(pseud_id.to_string())
                .fetch_optional(db.sqlite_pool().expect("sqlite handle"))
                .await?
        }
        Backend::Postgres => {
            sqlx::query_as(&sql)
                .bind(slot_id)
                .bind(pseud_id.to_string())
                .fetch_optional(db.postgres_pool().expect("postgres handle"))
                .await?
        }
    };

    let Some((
        id,
        work_id,
        position,
        reasons_json,
        taste_signal,
        seeded_by,
        recipe_stage,
        instance_curation,
        blend_score,
        created_at,
    )) = row
    else {
        return Ok(None);
    };

    // A reason outside the vocabulary is dropped rather than passed through, so
    // a row written by a newer version explains itself with what this version
    // understands instead of rendering a string it cannot vouch for.
    let parsed: Vec<SlotReason> = serde_json::from_str::<Vec<String>>(&reasons_json)
        .unwrap_or_default()
        .iter()
        .filter_map(|s| SlotReason::parse(s))
        .collect();

    Ok(Some(SlotExplanation {
        slot_id: id,
        work_id,
        position,
        reasons: SlotExplanation::normalized(parsed),
        taste_signal: taste_signal.as_deref().and_then(TasteSignal::parse),
        seeded_by,
        recipe_stage,
        instance_curation: InstanceCuration::parse(&instance_curation)
            .and_then(|c| c.reader_phrase())
            .map(str::to_string),
        blend_score,
        served_at: created_at,
    }))
}

