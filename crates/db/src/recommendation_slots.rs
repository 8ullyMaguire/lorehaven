/// Whether this reader has switched the attention report on.
///
/// Absent row means off, which is the spec's default: "off by default", "stays
/// disabled until the reader enables it".
pub async fn attention_enabled(db: &Database, pseud_id: Uuid) -> Result<bool> {
    let sql = db.sql(
        "SELECT enabled FROM reader_attention_settings WHERE pseud_id = ?",
        "SELECT enabled FROM reader_attention_settings WHERE pseud_id = ?::uuid",
    );
    let row: Option<(bool,)> = match db.backend() {
        Backend::Sqlite => {
            sqlx::query_as(&sql)
                .bind(pseud_id.to_string())
                .fetch_optional(db.sqlite_pool().expect("sqlite handle"))
                .await?
        }
        Backend::Postgres => {
            sqlx::query_as(&sql)
                .bind(pseud_id.to_string())
                .fetch_optional(db.postgres_pool().expect("postgres handle"))
                .await?
        }
    };
    Ok(row.map(|(e,)| e).unwrap_or(false))
}

