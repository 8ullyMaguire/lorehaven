    #[test]
    fn a_record_serializes_its_reasons_as_the_vocabulary_wire_forms() {
        // The persisted shape is what a future version has to read, so it is
        // pinned here rather than left to the SQL.
        let rec = SlotRecord {
            pseud_id: Uuid::nil(),
            work_id: Uuid::nil(),
            request_id: Uuid::nil(),
            position: 0,
            reasons: vec![SlotReason::TasteTags, SlotReason::Popular],
            taste_signal: Some(TasteSignal::Strong),
            seeded_by: None,
            recipe_stage: None,
            instance_curation: InstanceCuration::NotInvolved,
            blend_score: 0,
        };
        let json =
            serde_json::to_string(&rec.reasons.iter().map(|r| r.as_str()).collect::<Vec<_>>())
                .expect("serialize");
        assert_eq!(json, r#"["taste_tags","popular"]"#);
    }

    #[test]
    fn an_unknown_reason_stored_in_a_row_is_dropped_not_rendered() {
        // This is what `explain_slot` does with a reason it cannot parse.
        let stored = vec!["taste_tags".to_string(), "operator_boost".to_string()];
        let parsed: Vec<SlotReason> = stored.iter().filter_map(|s| SlotReason::parse(s)).collect();
        assert_eq!(parsed, vec![SlotReason::TasteTags]);
    }

    #[test]
    fn a_corrupt_reasons_column_degrades_to_no_reasons() {
        // A row whose JSON is not an array must not 500 the explanation door.
        let parsed: Vec<SlotReason> = serde_json::from_str::<Vec<String>>("{not json")
            .unwrap_or_default()
            .iter()
            .filter_map(|s| SlotReason::parse(s))
            .collect();
        assert!(parsed.is_empty());
    }
