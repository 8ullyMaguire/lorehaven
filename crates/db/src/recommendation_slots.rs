/// Insert a proposal into the queue, returning its id.
///
/// The trust levels are captured here rather than read back later, because
/// trust can change and §19.1's gate has to be judged on the value that was in
/// force when the proposal was made and when it was approved.
pub async fn propose_wrangling(
    db: &Database,
    kind: WranglingKind,
    from_node_id: &str,
    to_node_id: Option<&str>,
    reason: &str,
    proposed_by: Uuid,
    proposer_trust: i64,
) -> Result<String> {
    let id = Uuid::new_v4().to_string();
    let now = crate::identity::now_rfc3339();
    let sql = db.sql(
        "INSERT INTO tag_wrangling_proposals
           (id, kind, from_node_id, to_node_id, reason, proposed_by, proposer_trust,
            status, created_at)
         VALUES (?, ?, ?, ?, ?, ?, ?, 'pending', ?)",
        "INSERT INTO tag_wrangling_proposals
           (id, kind, from_node_id, to_node_id, reason, proposed_by, proposer_trust,
            status, created_at)
         VALUES (?::uuid, ?, ?, ?, ?, ?::uuid, ?, 'pending', ?::timestamptz)",
    );
    match db.backend() {
        Backend::Sqlite => {
            sqlx::query(&sql)
                .bind(&id)
                .bind(kind.as_str())
                .bind(from_node_id)
                .bind(to_node_id)
                .bind(reason)
                .bind(proposed_by.to_string())
                .bind(proposer_trust)
                .bind(&now)
                .execute(db.sqlite_pool().expect("sqlite handle"))
                .await?;
        }
        Backend::Postgres => {
            sqlx::query(&sql)
                .bind(&id)
                .bind(kind.as_str())
                .bind(from_node_id)
                .bind(to_node_id)
                .bind(reason)
                .bind(proposed_by.to_string())
                .bind(proposer_trust)
                .bind(&now)
                .execute(db.postgres_pool().expect("postgres handle"))
                .await?;
        }
    }
    Ok(id)
}

/// Read one proposal, scoped to nothing — operators and the queue share it,
/// but §33.3 says no *proposal or vote* is visible in another **user's**
/// surface, so a pending queue is a moderation surface, not a personal one.
/// `approved_by` is never returned to a non-approver.
pub async fn get_wrangling_proposal(db: &Database, id: &str) -> Result<Option<WranglingProposal>> {
    let sql = db.sql(
        "SELECT id, kind, from_node_id, to_node_id, reason, status,
                proposer_trust, approver_trust, created_at
           FROM tag_wrangling_proposals WHERE id = ?",
        "SELECT id::text, kind, from_node_id, to_node_id, reason, status,
                proposer_trust::bigint AS proposer_trust, approver_trust::bigint AS approver_trust,
                created_at::text AS created_at
           FROM tag_wrangling_proposals WHERE id = ?::uuid",
    );
    let row: Option<(
        String,
        String,
        String,
        Option<String>,
        String,
        String,
        i64,
        Option<i64>,
        String,
    )> = match db.backend() {
        Backend::Sqlite => {
            sqlx::query_as(&sql)
                .bind(id)
                .fetch_optional(db.sqlite_pool().expect("sqlite handle"))
                .await?
        }
        Backend::Postgres => {
            sqlx::query_as(&sql)
                .bind(id)
                .fetch_optional(db.postgres_pool().expect("postgres handle"))
                .await?
        }
    };
    Ok(row.map(
        |(id, kind, from, to, reason, status, ptrust, atrust, created_at)| WranglingProposal {
            id,
            kind: WranglingKind::parse(&kind).unwrap_or(WranglingKind::Alias),
            from_node_id: from,
            to_node_id: to,
            reason,
            status,
            proposer_trust: ptrust,
            approver_trust: atrust,
            created_at,
        },
    ))
}

